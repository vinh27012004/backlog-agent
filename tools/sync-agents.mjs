#!/usr/bin/env node
// Sinh phần agent của pack từ agents/ (nguồn duy nhất, đội sửa prompt ở đó):
//   agents/rules/common.md + agents/roles/<role>.md  → pack/agents/team-<role>.toml (subagent native của Codex)
//   agents/skills/<type>/SKILL.md                    → pack/skills/backlog-<type>/SKILL.md
//   agents/references/*.md                           → pack/skills/backlog-references/
//   agents/stacks/*.md                               → pack/skills/stack-notes/
//   agents/schemas/*.schema.json                     → pack/contracts/
// Phần chỉ đúng với runtime cũ (codex exec, --output-schema, tool runner) được thay ở đây,
// agents/ giữ nguyên cho orchestrator Python cũ. Chạy: node tools/sync-agents.mjs [--check]
import { existsSync, mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const SRC = join(ROOT, 'agents');
const PACK = join(ROOT, 'pack');
const CHECK = process.argv.includes('--check');
const HEADER = 'Generated by tools/sync-agents.mjs from agents/. Edit agents/ and rerun the script.';

// Runtime cũ chèn skill/tham khảo vào prompt; ở pack agent phải tự mở file, và chỉ mở file được chỉ đích danh
// (Practice #5 BC3JL6ZC: fixer BUG-01 bỏ bug-patterns, không ai đọc retry-playbook, reviewer không đọc skill nào).
const REF = '.agents/skills/backlog-references';
const ROLES = [
  { role: 'fixer', file: 'fixer.md', schema: 'fix-result', readOnly: false,
    description: 'Developer: analyses and implements one backlog item (TASK, CR, BUG or PI) inside the worktree named in the brief, then writes a fix-result JSON.',
    reads: ['Before you start, read the skill named in the brief (`.agents/skills/backlog-<type>/SKILL.md`) and the stack notes;',
      `a BUG also \`${REF}/bug-patterns.md\`, a PI also \`${REF}/pi-triage.md\`.`,
      `When the brief has \`<previous_attempt>\`, read \`${REF}/retry-playbook.md\` first and follow the row for its failKind.`,
      // CV8WV1JM, BC3JL6ZC, HIET12OA: mẹo chụp evidence chỉ nằm trong skill root, fixer không thấy.
      `Before the first MVS scenario that needs a screenshot, a running app or scenario data, read \`${REF}/evidence-playbook.md\`.`] },
  { role: 'reviewer', file: 'reviewer.md', schema: 'review', readOnly: true,
    description: 'Read-only reviewer: checks a candidate change for problems that build, tests and MVS cannot see, then writes a review JSON.',
    reads: ['Before you start, read the skill named in the brief (`.agents/skills/backlog-<type>/SKILL.md`): its done-conditions',
      'and traps are what R1, R2 and R5 judge against. Read the stack notes when the brief names them.'] },
  // Tester của guide (§2): chạy gate qua proxy tới helper của root (05 §5.22), chỉ được sửa answers/<ID>/submit.json.
  { role: 'verifier', file: 'verifier.md', schema: 'verification', readOnly: false,
    description: 'Tester: runs the team gate on one fixer attempt through team_runtime, checks the answer against the MVS, then writes a verification JSON.',
    reads: ['You change no code, tests or evidence; the only file you may edit is `answers/<ID>/submit.json` (step 3 below).'] },
  { role: 'pi-hypothesis', file: 'pi-hypothesis.md', schema: 'hypothesis', readOnly: true,
    description: 'Read-only investigator for a stuck production incident or a disputed answer: checks exactly one hypothesis, or solves an answer-only item independently, then writes a hypothesis JSON.',
    reads: [`Before you start, read \`${REF}/pi-triage.md\` (what evidence decides each kind of cause) and the stack notes`,
      'when the brief names them.'] }
];

// Thay section theo tiêu đề "## ..." của rules/common.md.
const COMMON_SECTIONS = {
  'Working environment': [
    '- You are a subagent spawned by the team orchestrator inside the MTM Player Codex session.',
    '  Work only inside the worktree / match folder named in your brief. Never touch sibling folders.',
    '- Do not call Game Master, Admin or Grader URLs. Company systems are queried by the orchestrator;',
    '  what it found is in your brief inside `<company_facts>` and is authoritative. On a PI you may also look',
    '  things up yourself (`company_tools`, then `company_call`): lookups only (logs, tickets, standards), never a',
    '  tool that creates or changes data, and at most about 10 calls (the whole team shares one rate limit).',
    '- Network is for installing a dependency only when the item requires it (report it in `needs_dependency`).',
    '- Do not run `git commit`, `git push`, `git reset`, `git checkout` or change branches. The orchestrator owns git.',
    '- Find code with the codegraph MCP tools before `rg` or opening whole files, always with `projectPath` =',
    '  `matchRoot` from `<worktree>` (your worktree has its own index; never query another folder): `codegraph_explore`',
    '  answers "where / how does X work" with the source in one call, `codegraph_search` finds a name,',
    '  `codegraph_callers` / `codegraph_callees` / `codegraph_impact` follow calls, `codegraph_node` reads one symbol.',
    '  Results point at the calling function, not the exact call line. Codegraph does not see properties inside a',
    '  call (tRPC procedures in `createTRPCRouter({...})`) or calls through client proxies (`api.card.create.useMutation`):',
    '  use `rg` for those, for text that is not a symbol (messages, config keys, SQL, CSS classes), and when codegraph',
    '  says the project is not indexed.',
    '- Never use computer use, desktop control or the operator\'s browser windows. For screenshots use the',
    '  `capture_evidence` tool against the app that the `app` tool started for your worktree.',
    '- Evidence budget: one `capture_evidence` call per MVS scenario, with the whole flow (login, navigation,',
    '  actions, `assertText`, `screenshot`) in its `steps` and a `browserProfile` to keep the login; never drive',
    '  the UI one step per call. A failed call: fix the steps, at most 2 retries per scenario, then record that',
    '  scenario as `NOT_RUN` with the reason and go on. Spend at most a third of your time on evidence. Write your',
    '  own Playwright/CDP script only for what `capture_evidence` cannot do (file download, API-only check), keep it',
    '  under `<checkoutRoot>/.team-work/scratch/<ID>/` (never in the match folder) and fix it at most twice.',
    '- A scenario about how the app handles a failing server (error status, timeout, offline, slow network): add a',
    '  `route` step to `capture_evidence` before the action that triggers the request (e.g. `{action: "route", url:',
    '  "/api/invoices/export", status: 500, times: 1}` or `abort: "TimedOut"` or `delayMs`), never change code, stop',
    '  the server or the database to cause it. Write in the scenario note and `engineeringRecord` that the failure was',
    '  simulated in the browser (the result lists it in `routed`). A bug the app shows by normal use needs no `route`.',
    '- Scenario data: every worktree\'s app uses the same database. Before running a seed script or creating data',
    '  through the app, call `app_data {action: "lock", backlogItemKey, waitSeconds: 50}` and repeat while it returns',
    '  `locked: false`; call `app_data {action: "unlock"}` once the evidence or report that reads the data is written.',
    '  Run the seed the MVS names, then the data scenarios in MVS order in one pass (later scenarios often use records',
    '  an earlier one created). A step went wrong (wrong click, wrong value, a record in an unexpected state such as',
    '  VOID): stop, re-run the seed only if the script says it is safe to re-run (otherwise mark the scenarios',
    '  `NOT_RUN`), then redo the data scenarios from the first one. Never continue on damaged data and never create',
    '  records the MVS did not ask for.',
    '- Do not send progress messages to the orchestrator: your final reply reaches it automatically. Message it',
    '  only when you are blocked on a decision that only it can make.'
  ].join('\n'),
  'Cost and output': [
    '- Every token costs money from a fixed team budget. Read only what you need; keep tool output short',
    '  (use filters, `Select-Object -First`, targeted test runs).',
    '- Finish by writing ONE JSON object that matches `contracts/{schema}.schema.json` (in',
    '  `team-sdlc-pack/runtime/`) to the results path given in your brief, then reply with exactly that JSON.',
    '  Write human-readable fields in the same language as the item.'
  ].join('\n')
};

// Tool của runtime cũ chưa từng được dựng: thay bằng cách làm có thật trong pack.
const REWRITES = [
  [/if the `runner` tool offers `mvs_run`, run it/g, 'run each MVS scenario from the brief'],
  [/`runner\.mvs_run`(?: if available)?/g, 'the MVS scenarios in the brief'],
  [/`runner\.app_call`/g, 'a local HTTP call to the app you started'],
  [/through the runner tool/g, 'with a local HTTP call to the app you started'],
  [/`<bug_patterns>`(?: below)?/g, '`.agents/skills/backlog-references/bug-patterns.md`'],
  [/`<pi_triage>`(?: below)?/g, '`.agents/skills/backlog-references/pi-triage.md`'],
  // Pack không reset worktree giữa các lần thử: lần sau thấy thay đổi của lần trước.
  [/The worktree was reset to a clean(\r?\n)branch, so the previous change is gone; the condensed log and signature are what remain\./g,
    'The worktree still holds the previous$1attempt\'s change (`git diff HEAD`): keep what is right and change what the failure points at.']
];

const rewrite = text => REWRITES.reduce((t, [re, to]) => t.replace(re, to), text);
// Checkout trên Windows (core.autocrlf=true) có thể là CRLF: khi đó `^---\n` không khớp và skill sinh ra
// mất dòng HEADER, nên mọi file đọc vào đều đổi về LF.
const read = path => readFileSync(path, 'utf8').replace(/\r\n/g, '\n');

function commonRules(schema) {
  const text = read(join(SRC, 'rules', 'common.md'));
  const parts = text.split(/^(?=## )/m);
  return parts.map(part => {
    const title = part.match(/^## (.+)$/m)?.[1]?.trim();
    if (title && COMMON_SECTIONS[title]) return `## ${title}\n${COMMON_SECTIONS[title].replace('{schema}', schema)}\n\n`;
    return part;
  }).join('');
}

function tomlLiteral(text) {
  if (text.includes("'''")) throw new Error("prompt contains ''' which TOML literal strings cannot hold");
  return `'''\n${text.trim()}\n'''`;
}

const outputs = new Map();     // path → nội dung

for (const r of ROLES) {
  const name = `team_${r.role.replace(/-/g, '_')}`;
  const body = [
    `You are the ${r.role} subagent of the team. Your brief from the orchestrator contains tagged blocks`,
    '(`<item>`, `<item_meta>`, `<triage>`, `<project_profile>`, `<company_facts>`, `<materials>`, `<recent_changes>`,',
    '`<previous_attempt>`, `<hypothesis>`, `<independent_answer>`, `<fix_result>`, `<diff>`, `<gate_findings>`, `<baseline_failures>`, `<requirements>`,',
    '`<worktree>`, `<results_path>`): use the ones present.',
    ...(r.readOnly ? ['You are READ-ONLY: do not modify, create or delete any file except your results JSON.'] : []),
    ...r.reads,
    '',
    rewrite(commonRules(r.schema)),
    rewrite(read(join(SRC, 'roles', r.file)))
  ].join('\n');
  outputs.set(join(PACK, 'agents', `team-${r.role}.toml`),
    `# ${HEADER}\nname = "${name}"\ndescription = "${r.description}"\ndeveloper_instructions = ${tomlLiteral(body)}\n`);
}

for (const type of readdirSync(join(SRC, 'skills'))) {
  const text = read(join(SRC, 'skills', type, 'SKILL.md'));
  outputs.set(join(PACK, 'skills', `backlog-${type}`, 'SKILL.md'), rewrite(text).replace(/^---\n/, `---\n# ${HEADER}\n`));
}

const refs = readdirSync(join(SRC, 'references')).filter(f => f.endsWith('.md'));
outputs.set(join(PACK, 'skills', 'backlog-references', 'SKILL.md'), [
  '---', 'name: backlog-references', 'description: Reference notes for fixers: bug patterns, PI triage checklist, the retry playbook and the evidence playbook.', '---', '',
  `<!-- ${HEADER} -->`, '', ...refs.map(f => `- \`${f}\``), ''].join('\n'));
for (const f of refs) outputs.set(join(PACK, 'skills', 'backlog-references', f), rewrite(read(join(SRC, 'references', f))));

const stacks = readdirSync(join(SRC, 'stacks')).filter(f => f.endsWith('.md'));
outputs.set(join(PACK, 'skills', 'stack-notes', 'SKILL.md'), [
  '---', 'name: stack-notes', 'description: Stack-specific pitfalls and commands (java, node, python, dotnet, go, php, unknown). Read the one matching detect_profile.', '---', '',
  `<!-- ${HEADER} -->`, '', ...stacks.map(f => `- \`${f}\``), ''].join('\n'));
for (const f of stacks) outputs.set(join(PACK, 'skills', 'stack-notes', f), rewrite(read(join(SRC, 'stacks', f))));

for (const f of readdirSync(join(SRC, 'schemas')).filter(f => f.endsWith('.schema.json'))) {
  outputs.set(join(PACK, 'contracts', f), read(join(SRC, 'schemas', f)));
}

// Còn sót tool cũ thì báo lỗi, để prompt không trỏ tới thứ không tồn tại.
const stale = [...outputs].filter(([, text]) => /\b(code_graph|mvs_run|app_call|output schema|system[ _-]?map)\b|web_search/i.test(text)).map(([p]) => p);
if (stale.length) { console.error(`stale references to legacy tools in:\n${stale.join('\n')}`); process.exit(1); }

let changed = 0;
for (const [path, text] of outputs) {
  const old = existsSync(path) ? read(path) : null;
  if (old === text) continue;
  changed++;
  if (CHECK) { console.error(`out of date: ${path}`); continue; }
  mkdirSync(dirname(path), { recursive: true });
  writeFileSync(path, text, 'utf8');
}
if (!CHECK && existsSync(join(PACK, 'agents', 'team-feature-worker.toml'))) rmSync(join(PACK, 'agents', 'team-feature-worker.toml'));
console.log(`${outputs.size} files, ${changed} ${CHECK ? 'out of date' : 'written'}`);
process.exit(CHECK && changed ? 1 : 0);
