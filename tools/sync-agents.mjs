#!/usr/bin/env node
// Sinh phần agent của pack từ agents/ (nguồn duy nhất, đội sửa prompt ở đó):
//   agents/rules/common.md + agents/roles/<role>.md  → pack/agents/team-<role>.toml (subagent native của Codex)
//   agents/skills/<type>/SKILL.md                    → pack/skills/backlog-<type>/SKILL.md
//   agents/references/*.md                           → pack/skills/backlog-references/
//   agents/stacks/*.md                               → pack/skills/stack-notes/
//   agents/schemas/*.schema.json                     → pack/contracts/
// Phần chỉ đúng với runtime cũ (codex exec, --output-schema, tool codegraph/runner) được thay ở đây,
// agents/ giữ nguyên cho orchestrator Python cũ. Chạy: node tools/sync-agents.mjs [--check]
import { existsSync, mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const SRC = join(ROOT, 'agents');
const PACK = join(ROOT, 'pack');
const CHECK = process.argv.includes('--check');
const HEADER = 'Generated by tools/sync-agents.mjs from agents/. Edit agents/ and rerun the script.';

const ROLES = [
  { role: 'fixer', file: 'fixer.md', schema: 'fix-result', readOnly: false,
    description: 'Developer: analyses and implements one backlog item (TASK, CR, BUG or PI) inside the worktree named in the brief, then writes a fix-result JSON.' },
  { role: 'reviewer', file: 'reviewer.md', schema: 'review', readOnly: true,
    description: 'Read-only reviewer: checks a candidate change for problems that build, tests and MVS cannot see, then writes a review JSON.' },
  { role: 'pi-hypothesis', file: 'pi-hypothesis.md', schema: 'hypothesis', readOnly: true,
    description: 'Read-only investigator for a stuck production incident: checks exactly one hypothesis, then writes a hypothesis JSON.' }
];

// Thay section theo tiêu đề "## ..." của rules/common.md.
const COMMON_SECTIONS = {
  'Working environment': [
    '- You are a subagent spawned by the team orchestrator inside the MTM Player Codex session.',
    '  Work only inside the worktree / match folder named in your brief. Never touch sibling folders.',
    '- Do not call Game Master, Admin or Grader URLs. Company systems are queried by the orchestrator;',
    '  what it found is in your brief inside `<company_facts>` and is authoritative.',
    '- Network is for installing a dependency only when the item requires it (report it in `needs_dependency`).',
    '- Do not run `git commit`, `git push`, `git reset`, `git checkout` or change branches. The orchestrator owns git.',
    '- Never use computer use, desktop control or the operator\'s browser windows. For screenshots use the',
    '  `capture_evidence` tool if available, otherwise Playwright/Edge headless against an app you started yourself.'
  ].join('\n'),
  'Cost and output': [
    '- Every token costs money from a fixed team budget. Read only what you need; keep tool output short',
    '  (use filters, `Select-Object -First`, targeted test runs).',
    '- Finish by writing ONE JSON object that matches `contracts/{schema}.schema.json` (in',
    '  `team-sdlc-pack/runtime/`) to the results path given in your brief, then reply with exactly that JSON.',
    '  Write human-readable fields in the same language as the item.'
  ].join('\n')
};

// Tool của runtime cũ chưa từng được dựng: thay bằng cách làm có thật trong pack.
const REWRITES = [
  [/if the `runner` tool offers `mvs_run`, run it/g, 'run each MVS scenario from the brief'],
  [/`runner\.mvs_run`(?: if available)?/g, 'the MVS scenarios in the brief'],
  [/`runner\.app_call`/g, 'a local HTTP call to the app you started'],
  [/through the runner tool/g, 'with a local HTTP call to the app you started'],
  [/Use `codegraph` \(callers, callees, impact\)/g, 'Use code search (`rg` for callers, imports and call sites)'],
  [/`codegraph`/g, 'code search (`rg`)'],
  [/\bcodegraph\b/g, 'code search'],
  [/`<bug_patterns>`(?: below)?/g, '`.agents/skills/backlog-references/bug-patterns.md`'],
  [/`<pi_triage>`(?: below)?/g, '`.agents/skills/backlog-references/pi-triage.md`'],
  [/Prefer the team MCP tools \(codegraph, runner\)[^\n]*\n?/g, '']
];

const rewrite = text => REWRITES.reduce((t, [re, to]) => t.replace(re, to), text);

function commonRules(schema) {
  const text = readFileSync(join(SRC, 'rules', 'common.md'), 'utf8');
  const parts = text.split(/^(?=## )/m);
  return parts.map(part => {
    const title = part.match(/^## (.+)$/m)?.[1]?.trim();
    if (title && COMMON_SECTIONS[title]) return `## ${title}\n${COMMON_SECTIONS[title].replace('{schema}', schema)}\n\n`;
    return part;
  }).join('');
}

function tomlLiteral(text) {
  if (text.includes("'''")) throw new Error("prompt contains ''' which TOML literal strings cannot hold");
  return `'''\n${text.trim()}\n'''`;
}

const outputs = new Map();     // path → nội dung

for (const r of ROLES) {
  const name = `team_${r.role.replace(/-/g, '_')}`;
  const body = [
    `You are the ${r.role} subagent of the team. Your brief from the orchestrator contains tagged blocks`,
    '(`<item>`, `<item_meta>`, `<triage>`, `<project_profile>`, `<company_facts>`, `<previous_attempt>`,',
    '`<hypothesis>`, `<fix_result>`, `<diff>`, `<worktree>`, `<results_path>`): use the ones present.',
    r.readOnly ? 'You are READ-ONLY: do not modify, create or delete any file except your results JSON.' :
      'Read the skill named in the brief (`.agents/skills/backlog-<type>/SKILL.md`) and the stack notes before you start.',
    '',
    rewrite(commonRules(r.schema)),
    rewrite(readFileSync(join(SRC, 'roles', r.file), 'utf8'))
  ].join('\n');
  outputs.set(join(PACK, 'agents', `team-${r.role}.toml`),
    `# ${HEADER}\nname = "${name}"\ndescription = "${r.description}"\ndeveloper_instructions = ${tomlLiteral(body)}\n`);
}

for (const type of readdirSync(join(SRC, 'skills'))) {
  const text = readFileSync(join(SRC, 'skills', type, 'SKILL.md'), 'utf8');
  outputs.set(join(PACK, 'skills', `backlog-${type}`, 'SKILL.md'), rewrite(text).replace(/^---\n/, `---\n# ${HEADER}\n`));
}

const refs = readdirSync(join(SRC, 'references')).filter(f => f.endsWith('.md'));
outputs.set(join(PACK, 'skills', 'backlog-references', 'SKILL.md'), [
  '---', 'name: backlog-references', 'description: Reference notes for fixers: bug patterns, PI triage checklist and the retry playbook.', '---', '',
  `<!-- ${HEADER} -->`, '', ...refs.map(f => `- \`${f}\``), ''].join('\n'));
for (const f of refs) outputs.set(join(PACK, 'skills', 'backlog-references', f), rewrite(readFileSync(join(SRC, 'references', f), 'utf8')));

const stacks = readdirSync(join(SRC, 'stacks')).filter(f => f.endsWith('.md'));
outputs.set(join(PACK, 'skills', 'stack-notes', 'SKILL.md'), [
  '---', 'name: stack-notes', 'description: Stack-specific pitfalls and commands (java, node, python, dotnet, go, php, unknown). Read the one matching detect_profile.', '---', '',
  `<!-- ${HEADER} -->`, '', ...stacks.map(f => `- \`${f}\``), ''].join('\n'));
for (const f of stacks) outputs.set(join(PACK, 'skills', 'stack-notes', f), rewrite(readFileSync(join(SRC, 'stacks', f), 'utf8')));

for (const f of readdirSync(join(SRC, 'schemas')).filter(f => f.endsWith('.schema.json'))) {
  outputs.set(join(PACK, 'contracts', f), readFileSync(join(SRC, 'schemas', f), 'utf8'));
}

// Còn sót tool cũ thì báo lỗi, để prompt không trỏ tới thứ không tồn tại.
const stale = [...outputs].filter(([, text]) => /\b(codegraph|mvs_run|app_call|output schema)\b|web_search/.test(text)).map(([p]) => p);
if (stale.length) { console.error(`stale references to legacy tools in:\n${stale.join('\n')}`); process.exit(1); }

let changed = 0;
for (const [path, text] of outputs) {
  const old = existsSync(path) ? readFileSync(path, 'utf8') : null;
  if (old === text) continue;
  changed++;
  if (CHECK) { console.error(`out of date: ${path}`); continue; }
  mkdirSync(dirname(path), { recursive: true });
  writeFileSync(path, text, 'utf8');
}
if (!CHECK && existsSync(join(PACK, 'agents', 'team-feature-worker.toml'))) rmSync(join(PACK, 'agents', 'team-feature-worker.toml'));
console.log(`${outputs.size} files, ${changed} ${CHECK ? 'out of date' : 'written'}`);
process.exit(CHECK && changed ? 1 : 0);
